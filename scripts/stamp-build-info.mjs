// scripts/stamp-build-info.mjs — stamp src/build-info.ts from git + package.json.
//
// Runs in DEV (dev.sh's `build:incremental`, or a manual `pnpm run build`) so the
// committed build-info.ts stays fresh. It records the engine's build identity:
// package version + git short SHA + commit date. Provenance only (which engine a
// bundle was built with / a save was authored against); compatibility gating keys
// on INTERFACE_VERSION, not this.
//
// It does NOT run in CI — the committed file is the source of truth there (stamped
// in dev before commit); a CI/Docker rebuild would only overwrite it with the
// runner's view, and Docker stages that COPY lib have no `.git` anyway.

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const target = here('../src/build-info.ts');

function git(...args) {
    return execFileSync('git', args, { cwd: here('..'), encoding: 'utf8' }).trim();
}

// CI ships the committed build-info.ts as-is. (If it's somehow absent, fall
// through and stamp so the build doesn't fail on a missing import.)
if (process.env.CI && existsSync(target)) {
    console.log('[stamp-build-info] CI — keeping committed build-info.ts');
    process.exit(0);
}

const { version } = JSON.parse(readFileSync(here('../package.json'), 'utf8'));
let sha = 'unknown';
let date = '00000000';
try {
    sha = git('rev-parse', '--short', 'HEAD');
    date = git('show', '-s', '--format=%cd', '--date=format:%Y%m%d', 'HEAD');
} catch {
    // No git (e.g. a Docker stage that COPYs lib without `.git`). Keep the
    // committed value rather than clobbering a real SHA with placeholders.
    if (existsSync(target)) {
        console.warn('[stamp-build-info] git unavailable — keeping committed build-info.ts');
        process.exit(0);
    }
    console.warn('[stamp-build-info] git unavailable and no committed build-info.ts — stamping placeholders');
}

const contents = `// GENERATED by scripts/stamp-build-info.mjs — do not edit by hand.
//
// The engine's build identity, stamped from git at \`pnpm run build\` time. Used
// for provenance: which exact engine a bundle was built with / a save was
// authored against. Compatibility gating keys on INTERFACE_VERSION, not this.

/** The engine package version (lib/package.json), the git short SHA, and the
 *  commit date (YYYYMMDD) the dist was built from. */
export const BONGLE_BUILD = {
    version: '${version}',
    sha: '${sha}',
    date: '${date}',
} as const;

/** Composed engine identity: the package semver with git build metadata appended
 *  (semver \`+build\` syntax), e.g. \`0.0.0-alpha.1+gacdf20a4.20260804\`. Forward-
 *  compatible with real semver — the core becomes meaningful when the package is
 *  versioned + published; the \`+g...\` metadata stays. */
export const BONGLE_VERSION = \`\${BONGLE_BUILD.version}+g\${BONGLE_BUILD.sha}.\${BONGLE_BUILD.date}\`;
`;

// Idempotent write: only touch the file when the content actually changes (a new
// commit). dev.sh's engine watcher fswatches lib/src and rebuilds on any change; an
// unconditional write here would bump build-info.ts's mtime every rebuild and retrigger
// the watcher, looping builds forever. Skipping the no-op write breaks that cycle.
if (existsSync(target) && readFileSync(target, 'utf8') === contents) {
    console.log(`[stamp-build-info] ${version}+g${sha}.${date} (unchanged)`);
    process.exit(0);
}
writeFileSync(target, contents);
console.log(`[stamp-build-info] ${version}+g${sha}.${date}`);
